// Self-hosts the homepage's icon fonts, cut down to the icons it uses.
//
// The homepage used to link Font Awesome 6.4.0 (all.min.css) and three
// Phosphor 2.1.2 weights (regular / bold / fill) from CDNs: 4 render-blocking
// cross-origin stylesheets and ~670 KB of woff2 (fa-solid 147 KB, fa-brands
// 106 KB, Phosphor 129-147 KB per weight) for ~25 + ~70 icons. This script
// scans the homepage sources for the icon classes they use, subsets each font
// to those glyphs, and writes:
//
//   public/fonts/icons/*.woff2   the subset fonts
//   src/styles/icon-faces.css    @font-face + base classes + used icon rules,
//                                copied from the original CSS (imported by
//                                portfolio.css)
//
// The project pages (project_XX.html) still link the CDN stylesheets and are
// not affected. Re-run after adding an icon to the homepage (from the repo
// root) — test/icon-faces.test.ts fails until you do:
//     node scripts/subset-icons.mjs
// Requires uv (runs fonttools' pyftsubset through uvx).
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { usedIconClasses } from './icon-usage.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = path.join(ROOT, 'public', 'fonts', 'icons');
const FA = 'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0';
const PH = 'https://cdn.jsdelivr.net/npm/@phosphor-icons/web@2.1.2/src';

// Plain `selectors { body }` rules plus at-rule blocks without nesting —
// all both stylesheets contain.
function parseRules(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const rules = [];
  for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    rules.push({ selectors: m[1].split(',').map(s => s.trim()).filter(Boolean), body: m[2].trim() });
  }
  return rules;
}
const fmt = (selectors, body) => `${selectors.join(',\n')} {\n  ${body.replace(/;\s*/g, ';\n  ').trim()}\n}`;
const codepoints = body => [...body.matchAll(/content:\s*"\\([0-9a-f]+)"/gi)].map(m => parseInt(m[1], 16));

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}
async function fetchFile(url, dst) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  fs.writeFileSync(dst, Buffer.from(await res.arrayBuffer()));
}

function subsetFont(src, dst, cps) {
  const unicodes = cps.map(c => c.toString(16)).join(',');
  execFileSync('uvx', ['--from', 'fonttools[woff]', 'pyftsubset', src, `--unicodes=${unicodes}`,
    '--flavor=woff2', `--output-file=${dst}`, '--no-hinting', '--layout-features=*'], { stdio: 'inherit' });
}

async function main() {
  const { fa, ph } = usedIconClasses(ROOT);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'icons-'));
  fs.mkdirSync(FONT_DIR, { recursive: true });
  const out = ['/* GENERATED by scripts/subset-icons.mjs -- do not edit by hand. */'];
  const report = [];

  // Font Awesome: solid (900) + brands (400) faces, the base classes, and the
  // ::before rule of each used icon (keeping only the used selector when an
  // icon and its aliases share one rule).
  const faBase = new Set(['.fa', '.fa-classic', '.fa-sharp', '.fas', '.fa-solid', '.far', '.fa-regular', '.fab', '.fa-brands', ':root', ':host']);
  const faFonts = { 'fa-solid-900': [], 'fa-brands-400': [] };
  let inBrands = false;
  for (const r of parseRules(await fetchText(`${FA}/css/all.css`))) {
    if (r.selectors[0] === '@font-face') {
      // The brand icons' rules sit between the Brands face and the next face.
      inBrands = /Font Awesome 6 Brands/.test(r.body);
      const file = r.body.match(/webfonts\/([\w-]+)\.woff2/)?.[1];
      if (!/Font Awesome 6/.test(r.body) || !(file in faFonts)) continue;
      out.push(fmt(['@font-face'], r.body.replace(/src:[^;]+/, `src: url("/fonts/icons/${file}.woff2") format("woff2")`)));
      continue;
    }
    if (r.selectors.every(s => faBase.has(s))) { out.push(fmt(r.selectors, r.body)); continue; }
    const used = r.selectors.filter(s => fa.has(s.match(/^\.(fa-[a-z0-9-]+)::?before$/)?.[1]));
    if (!used.length) continue;
    out.push(fmt(used, r.body));
    faFonts[inBrands ? 'fa-brands-400' : 'fa-solid-900'].push(...codepoints(r.body));
  }

  // Phosphor: one stylesheet per weight, each with its own font family, base
  // class (.ph / .ph-bold / .ph-fill) and `.<base>.ph-<name>:before` rules.
  const phFonts = {};
  for (const [dir, base, file] of [['regular', '.ph', 'Phosphor'], ['bold', '.ph-bold', 'Phosphor-Bold'], ['fill', '.ph-fill', 'Phosphor-Fill']]) {
    phFonts[file] = [];
    for (const r of parseRules(await fetchText(`${PH}/${dir}/style.css`))) {
      if (r.selectors[0] === '@font-face') {
        out.push(fmt(['@font-face'], r.body.replace(/src:[^;]+/, `src: url("/fonts/icons/${file}.woff2") format("woff2")`)));
      } else if (r.selectors.length === 1 && r.selectors[0] === base) {
        out.push(fmt(r.selectors, r.body));
      } else {
        const used = r.selectors.filter(s => ph.has(s.match(/^\.ph(?:-bold|-fill)?\.(ph-[a-z0-9-]+):before$/)?.[1]));
        if (!used.length) continue;
        out.push(fmt(used, r.body));
        phFonts[file].push(...codepoints(r.body));
      }
    }
  }

  for (const [file, cps] of Object.entries(faFonts)) {
    const src = path.join(tmp, `${file}.woff2`);
    await fetchFile(`${FA}/webfonts/${file}.woff2`, src);
    subsetFont(src, path.join(FONT_DIR, `${file}.woff2`), [...new Set(cps)]);
    report.push([file, src, cps.length]);
  }
  for (const [file, cps] of Object.entries(phFonts)) {
    const dir = { Phosphor: 'regular', 'Phosphor-Bold': 'bold', 'Phosphor-Fill': 'fill' }[file];
    const src = path.join(tmp, `${file}.woff2`);
    await fetchFile(`${PH}/${dir}/${file}.woff2`, src);
    subsetFont(src, path.join(FONT_DIR, `${file}.woff2`), [...new Set(cps)]);
    report.push([file, src, cps.length]);
  }
  fs.writeFileSync(path.join(ROOT, 'src', 'styles', 'icon-faces.css'), out.join('\n') + '\n');
  for (const [file, src, n] of report) {
    console.log(`${file}: ${n} glyphs, ${fs.statSync(src).size >> 10} KB -> ${fs.statSync(path.join(FONT_DIR, `${file}.woff2`)).size >> 10} KB`);
  }
  console.log(`${fa.size} Font Awesome + ${ph.size} Phosphor icon classes`);
  fs.rmSync(tmp, { recursive: true, force: true });
}

await main();
