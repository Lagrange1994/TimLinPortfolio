"""Split the self-hosted GenSen Rounded TW fonts into layers so the homepage
never downloads the full ~280 KB-per-weight files.

The full fonts are a ~1,200-glyph subset of the site's own characters (home
and project pages), but the homepage renders only part of them in any one
weight (~470 in regular, ~100 in medium, ~130 in bold). Per weight:

  GenSenRounded2TW-<w>.woff2       full font, unchanged, declared first; its
                                   unicode-range is exactly its own cmap, so
                                   a character the font lacks goes straight
                                   to Noto Sans TC instead of downloading it
  GenSenRounded2TW-<w>-page.woff2  what the homepage renders in that weight
                                   (scripts/gensen-homepage-chars.json),
                                   minus the hero characters
  GenSenRounded2TW-<w>-hero.woff2  first-screen characters (nav, loader,
                                   hero copy), preloaded, declared last

Later faces win where ranges overlap, so the full file is only fetched for a
character neither layer has (project pages, chat replies).

Also writes the @font-face rules: src/styles/gensen-faces.css (all layers,
imported by portfolio.css) and src/styles/gensen-faces-full.css (the full
files only, no unicode-range, imported by projects-tailwind.css: the project
pages keep their own font setup, untouched by the homepage layers). Re-run after changing homepage copy
(re-collect first: scripts/collect-gensen-chars.mjs), from the repo root:
    uvx --from "fonttools[woff]" python scripts/subset-fonts.py
"""
import json
import os
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
FONT_DIR = os.path.join(ROOT, 'public', 'fonts', 'gensen-rounded-tw')
WEIGHT_CSS = {'EL': 200, 'L': 300, 'R': 400, 'M': 500, 'B': 700, 'H': 900}
# Text keys (src/i18n/translations.ts) visible on the first screen.
HERO_KEY = re.compile(r"\b((?:nav|loader|hero)_\w+):\s*(['\"`])((?:\.|(?!\2).)*)\2", re.S)


def hero_chars():
    with open(os.path.join(ROOT, 'src', 'i18n', 'translations.ts'), encoding='utf8') as f:
        src = f.read()
    chars = set()
    for m in HERO_KEY.finditer(src):
        chars.update(m.group(3))
    chars |= {chr(c) for c in range(0x20, 0x7F)}       # ASCII
    chars |= {chr(c) for c in range(0x3000, 0x3040)}   # CJK punctuation
    chars |= {chr(c) for c in range(0xFF00, 0xFFF0)}   # full-width forms
    chars |= {chr(c) for c in range(0x2010, 0x2030)}   # dashes, quotes, ellipsis
    return {c for c in chars if c.isprintable()}


def unicode_range(chars):
    cps = sorted(ord(c) for c in chars)
    parts, start, prev = [], cps[0], cps[0]
    for cp in cps[1:] + [None]:
        if cp is not None and cp == prev + 1:
            prev = cp
            continue
        parts.append(f'U+{start:X}' if start == prev else f'U+{start:X}-{prev:X}')
        if cp is not None:
            start = prev = cp
    return ', '.join(parts)


# CSS weight -> the face the browser's font matching picks for it.
FACE_FOR_WEIGHT = {100: 'EL', 200: 'EL', 300: 'L', 400: 'R', 500: 'M', 600: 'B', 700: 'B', 800: 'H', 900: 'H'}


def page_chars():
    """Non-ASCII characters the homepage renders, per face (collected from the
    running page by scripts/collect-gensen-chars.mjs)."""
    with open(os.path.join(ROOT, 'scripts', 'gensen-homepage-chars.json'), encoding='utf8') as f:
        data = json.load(f)
    per_face = {}
    for weight, chars in data.items():
        per_face.setdefault(FACE_FOR_WEIGHT[int(weight)], set()).update(chars)
    return per_face


def save_subset(src, dst, chars, opts):
    font = TTFont(src)
    sub = subset.Subsetter(opts)
    sub.populate(text=''.join(sorted(chars)))
    sub.subset(font)
    font.flavor = 'woff2'
    font.save(dst)


def main():
    text = hero_chars()
    page = page_chars()
    print(f'{len(text)} hero characters')
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.notdef_outline = True
    opts.name_IDs = ['*']
    opts.hinting = False

    css = ['/* GENERATED by scripts/subset-fonts.py -- do not edit by hand. */']
    full_css = list(css)
    for w, weight in WEIGHT_CSS.items():
        src = os.path.join(FONT_DIR, f'GenSenRounded2TW-{w}.woff2')
        # A unicode-range may only claim characters the file really has: for
        # a claimed-but-missing one the browser falls through to the next
        # face and downloads it for nothing. That includes the full file:
        # with no range it claimed every character, so one the font lacks
        # (· → ↗ 徹 on the homepage) fetched all ~280 KB of it before
        # falling back to Noto Sans TC. Its range is exactly its own cmap.
        cmap = TTFont(src).getBestCmap()
        has = lambda chars: {c for c in chars if ord(c) in cmap}
        hero = has(text)
        layers = [('.woff2', {chr(c) for c in cmap})]
        page_only = has(page.get(w, set())) - hero
        if page_only:
            save_subset(src, os.path.join(FONT_DIR, f'GenSenRounded2TW-{w}-page.woff2'), page_only, opts)
            layers.append(('-page.woff2', page_only))
        save_subset(src, os.path.join(FONT_DIR, f'GenSenRounded2TW-{w}-hero.woff2'), hero, opts)
        layers.append(('-hero.woff2', hero))
        print(f'{w}: ' + ', '.join(
            f'{s[1:-6] or "full"} {len(c)} chars {os.path.getsize(os.path.join(FONT_DIR, f"GenSenRounded2TW-{w}{s}")) // 1024} KB'
            for s, c in layers))
        base = f'/fonts/gensen-rounded-tw/GenSenRounded2TW-{w}'
        full_css.append(
            "@font-face {\n  font-family: 'GenSen Rounded TW';\n"
            f"  src: url('{base}.woff2') format('woff2');\n"
            f'  font-weight: {weight};\n  font-style: normal;\n  font-display: swap;\n}}'
        )
        for suffix, chars in layers:
            extra = f'\n  unicode-range: {unicode_range(chars)};'
            css.append(
                "@font-face {\n  font-family: 'GenSen Rounded TW';\n"
                f"  src: url('{base}{suffix}') format('woff2');\n"
                f'  font-weight: {weight};\n  font-style: normal;\n  font-display: swap;{extra}\n}}'
            )
    with open(os.path.join(ROOT, 'src', 'styles', 'gensen-faces.css'), 'w', encoding='utf8') as f:
        f.write('\n'.join(css) + '\n')
    with open(os.path.join(ROOT, 'src', 'styles', 'gensen-faces-full.css'), 'w', encoding='utf8') as f:
        f.write('\n'.join(full_css) + '\n')


if __name__ == '__main__':
    main()
